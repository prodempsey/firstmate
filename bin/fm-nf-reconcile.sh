#!/usr/bin/env bash
# Reconcile local terminal task signals against durable FirstMate handling state.
#
# Usage:
#   fm-nf-reconcile.sh           Emit one check line while any item is unhandled.
#   fm-nf-reconcile.sh list      Print full detail for every current unhandled item.
#   fm-nf-reconcile.sh install   Install the persistent watcher check shim.
#
# Local state/<id>.meta plus the matching state/<id>.status are authoritative.
# The ledger format is one tab-separated task id and signal fingerprint per line.
# This Phase 1 command does not read or mutate board ownership.
set -eu

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"
LEDGER="$STATE/.nf-handled"
MODE=${1:-check}

# shellcheck disable=SC1091 # Dynamic sibling path is resolved from BASH_SOURCE.
. "$SCRIPT_DIR/fm-nf-lib.sh"

usage() {
  cat <<'EOF'
usage: fm-nf-reconcile.sh [list|install]

With no mode, emit one NEEDS FIRSTMATE line on every check while any local
terminal signal is absent from the handled ledger.
EOF
}

case "$MODE" in
  check)
    [ "$#" -eq 0 ] || { usage >&2; exit 2; }
    ;;
  list|install)
    [ "$#" -eq 1 ] || { usage >&2; exit 2; }
    ;;
  -h|--help)
    usage
    exit 0
    ;;
  *)
    usage >&2
    exit 2
    ;;
esac

write_if_changed() {  # <destination> <content>
  local destination=$1 content=$2
  if [ -f "$destination" ] && [ "$(cat "$destination" 2>/dev/null)" = "$content" ]; then
    return 0
  fi
  printf '%s\n' "$content" > "$destination"
}

install_check() {
  local shim body
  mkdir -p "$STATE"
  shim="$STATE/needs-firstmate.check.sh"
  body=$(cat <<EOF
#!/usr/bin/env bash
# Auto-generated by fm-nf-reconcile.sh install.
# The watcher runs this each check cycle and turns non-empty output into a wake.
export FM_HOME=$(printf '%q' "$FM_HOME")
export FM_STATE_OVERRIDE=$(printf '%q' "$STATE")
exec $(printf '%q' "$FM_ROOT/bin/fm-nf-reconcile.sh")
EOF
)
  write_if_changed "$shim" "$body"
  chmod +x "$shim"
  printf 'installed: %s\n' "$shim"
}

if [ "$MODE" = install ]; then
  install_check
  exit 0
fi

if [ ! -d "$STATE" ]; then
  printf 'fm-nf-reconcile: state directory not found: %s\n' "$STATE" >&2
  exit 1
fi

PENDING=$(mktemp "${TMPDIR:-/tmp}/fm-nf-pending.XXXXXX")
# shellcheck disable=SC2317,SC2329 # Invoked by the EXIT trap below.
cleanup() {
  rm -f "$PENDING"
}
trap cleanup EXIT

is_handled() {  # <task-id> <fingerprint>
  local id=$1 fingerprint=$2 key
  [ -f "$LEDGER" ] || return 1
  key=$(printf '%s\t%s' "$id" "$fingerprint")
  grep -Fqx -- "$key" "$LEDGER" 2>/dev/null
}

collect_unhandled() {
  local meta id fingerprint
  : > "$PENDING"
  for meta in "$STATE"/*.meta; do
    [ -f "$meta" ] || continue
    id=$(basename "$meta" .meta)
    fingerprint=$(fm_nf_current_fingerprint "$STATE" "$id") || continue
    is_handled "$id" "$fingerprint" && continue
    printf '%s\t%s\n' "$id" "$fingerprint" >> "$PENDING"
  done
  LC_ALL=C sort -o "$PENDING" "$PENDING"
}

meta_detail() {  # <meta-file> <key>
  local value
  value=$(fm_meta_get "$1" "$2")
  [ -n "$value" ] && printf '%s' "$value" || printf '-'
}

print_list() {
  local count id fingerprint meta status line verb
  count=$(wc -l < "$PENDING" | tr -d ' ')
  if [ "$count" -eq 0 ]; then
    printf 'NEEDS FIRSTMATE: none\n'
    return 0
  fi
  printf 'NEEDS FIRSTMATE: %s unhandled\n' "$count"
  while IFS=$'\t' read -r id fingerprint; do
    [ -n "$id" ] || continue
    meta="$STATE/$id.meta"
    status="$STATE/$id.status"
    line=$(last_status_line "$status")
    verb=$(fm_nf_signal_verb "$line")
    printf '\n%s\n' "$id"
    printf '  signal: %s\n' "$line"
    printf '  verb: %s\n' "$verb"
    printf '  fingerprint: %s\n' "$fingerprint"
    printf '  kind: %s\n' "$(meta_detail "$meta" kind)"
    printf '  project: %s\n' "$(meta_detail "$meta" project)"
    printf '  mode: %s\n' "$(meta_detail "$meta" mode)"
    printf '  yolo: %s\n' "$(meta_detail "$meta" yolo)"
    printf '  worktree: %s\n' "$(meta_detail "$meta" worktree)"
    printf '  pr: %s\n' "$(meta_detail "$meta" pr)"
    printf '  meta: %s\n' "$meta"
    printf '  status: %s\n' "$status"
  done < "$PENDING"
}

print_check_line() {
  local count shown=0 remaining id fingerprint summary=""
  count=$(wc -l < "$PENDING" | tr -d ' ')
  while IFS=$'\t' read -r id fingerprint; do
    [ -n "$id" ] || continue
    if [ "$shown" -lt 8 ]; then
      [ -z "$summary" ] || summary="$summary, "
      summary="$summary$id"
      shown=$((shown + 1))
    fi
  done < "$PENDING"
  remaining=$((count - shown))
  if [ "$remaining" -gt 0 ]; then
    summary="$summary, and $remaining more"
  fi
  printf 'NEEDS FIRSTMATE: %s unhandled - %s (run bin/fm-nf-reconcile.sh list; ack with bin/fm-nf-ack.sh <id>)\n' \
    "$count" "$summary"
}

collect_unhandled

if [ "$MODE" = list ]; then
  print_list
  exit 0
fi

if [ -s "$PENDING" ]; then
  print_check_line
fi
exit 0
